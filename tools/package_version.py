#!/usr/bin/env python3
"""Write the zynthian package store entries of the Eka plugins for a release, in package/Plugins/<Package>/:

    info.yml          title, version, icon, size, description (from the plugin's section of README.md)
    <Package>.sh      package script (zynthian-packages/zynpackage_lib.sh, type lv2_plugin)
    Art/<icon>.png    the plugin's first screenshot (plugins/<plugin>/docs/1-*.png)

They are copied as they are into the Plugins/ folder of zynthian-packages (see PACKAGING.md).

usage: tools/package_version.py VERSION [--repo OWNER/REPO]

VERSION is the release tag (e.g. 0.1): the CI publishes eka-<plugin>-lv2-<arch>.tar.gz in the GitHub release
with that name. The installed size is measured on the bundles built by tools/package.sh (dist/lv2), when they are
there; otherwise the size already in info.yml is kept.
"""

import argparse
import glob
import os
import re
import shutil
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG_DIR = os.path.join(ROOT, "package", "Plugins")

SCRIPT = """#!/bin/bash
# zynthian package script for {title} (zynthian-packages: Plugins/{title}), from the Eka plugins
# (https://github.com/{repo}). Installs the LV2 bundle eka-{plugin}.lv2, built by the repository's GitHub CI
# (x86_64 or arm64) and published in the release VERSION, into zynthian-plugins/lv2. The bundle has the zynthian
# widget (zyngui:widget){samples_note}.
#
# Generated by tools/package_version.py of {repo}: don't edit it here, run the tool for a new release.
#
# The work is done by the zynthian-packages library, so this script needs the catalog on the machine
# ($ZYNTHIAN_DIR/zynthian-packages): run it on a zynthian, or with ZYNTHIAN_DIR pointing to a folder that has a
# clone of zynthian-packages (the library is zynthian-packages/zynpackage_lib.sh).

source $ZYNTHIAN_DIR/zynthian-packages/zynpackage_lib.sh

PACKAGE_TYPE="lv2_plugin"
GITHUB="{repo}"
# Release tag
VERSION="{version}"
SYMBOL="eka-{plugin}"
PLUGIN_URI="{uri}"
# The widget (in the bundle), and its names in zyngui/widgets_user for zynthian versions that load widgets from
# there (Vangelis) instead of finding the zyngui:widget declared in the bundle
WIDGET="{widget}"
WIDGET_LINKS=({widget_links})
# Bank for the user presets (Zynthian's "New bank" needs the folder to exist), or empty
USER_PRESETS="{user_presets}"
{samples_var}
do_install() {{
    lv2_plugin_install || return
    local bundle="$ZYNTHIAN_PLUGINS_DIR/lv2/$SYMBOL.lv2"
    # Zynthian versions without zyngui:widget support find the widget by its name in widgets_user
    if [ -n "$WIDGET" ] && grep -qs widgets_user "$ZYNTHIAN_UI_DIR/zyngine/zynthian_engine_jalv.py"; then
        mkdir -p "$ZYNTHIAN_UI_DIR/zyngui/widgets_user"
        local link
        for link in "${{WIDGET_LINKS[@]}}"; do
            ln -sfn "$bundle/$WIDGET" "$ZYNTHIAN_UI_DIR/zyngui/widgets_user/$link"
        done
    fi
    # Factory samples (in the bundle) and the folder for the user's samples
    if [ -n "$SAMPLES" ]; then
        mkdir -p "$ZYNTHIAN_MY_DATA_DIR/files/Samples/$SAMPLES-user"
        if [ -L "$ZYNTHIAN_MY_DATA_DIR/files/Samples/$SAMPLES" ] || [ ! -e "$ZYNTHIAN_MY_DATA_DIR/files/Samples/$SAMPLES" ]; then
            ln -sfn "$bundle/samples" "$ZYNTHIAN_MY_DATA_DIR/files/Samples/$SAMPLES"
        fi
    fi
    # User presets bank
    if [ -n "$USER_PRESETS" ]; then
        local pset="$ZYNTHIAN_MY_DATA_DIR/presets/lv2/$USER_PRESETS.presets.lv2"
        mkdir -p "$pset"
        [ -s "$pset/manifest.ttl" ] || printf '%s\\n' \\
            '@prefix lv2:   <http://lv2plug.in/ns/lv2core#> .' \\
            '@prefix pset:  <http://lv2plug.in/ns/ext/presets#> .' \\
            '@prefix rdfs:  <http://www.w3.org/2000/01/rdf-schema#> .' > "$pset/manifest.ttl"
    fi
    # Factory presets in the preset list cache
    (cd "$ZYNTHIAN_UI_DIR" && python3 zyngine/zynthian_lv2.py presets "$PLUGIN_URI") >/dev/null 2>&1 || true
}}

do_uninstall() {{
    lv2_plugin_uninstall
    local link
    for link in "${{WIDGET_LINKS[@]}}"; do
        if [ -L "$ZYNTHIAN_UI_DIR/zyngui/widgets_user/$link" ]; then
            rm -f "$ZYNTHIAN_UI_DIR/zyngui/widgets_user/$link"
        fi
    done
    if [ -n "$SAMPLES" ] && [ -L "$ZYNTHIAN_MY_DATA_DIR/files/Samples/$SAMPLES" ]; then
        rm -f "$ZYNTHIAN_MY_DATA_DIR/files/Samples/$SAMPLES"
    fi
}}

zynpackage_main "$@"
"""

INFO = """title: "{title}"
version: "{version}"
{icon_line}author: "{author}"
license: "GPL-3.0-or-later"
source_url: "https://github.com/{repo}.git"
size: "{size}"
content: "zynthian-plugins/lv2/eka-{plugin}.lv2"
description: "{short}.<br/>

{long}
"
"""


def readme_sections():
    """{plugin: (title, subtitle, paragraph)} from the '### [Eka X](plugins/x): subtitle' sections of README.md"""
    with open(os.path.join(ROOT, "README.md"), encoding="utf-8") as f:
        text = f.read()
    res = {}
    for m in re.finditer(r"^### \[(.+?)\]\(plugins/(\w+)\): *(.+?)\n(.*?)(?=^#|\Z)", text, re.M | re.S):
        title, plugin, subtitle, body = m.groups()
        paras = [p.strip() for p in body.strip().split("\n\n") if p.strip() and not p.strip().startswith("![")]
        res[plugin] = (title, subtitle.strip(), " ".join(paras[0].split()) if paras else "")
    return res


def plugin_uri(plugin):
    with open(os.path.join(ROOT, "plugins", plugin, "lv2", "manifest.ttl"), encoding="utf-8") as f:
        ttl = f.read()
    return re.search(r"^<([^>]+)>\s*\n\s*a lv2:Plugin", ttl, re.M).group(1)


def installed_size(plugin):
    bundle = os.path.join(ROOT, "dist", "lv2", f"eka-{plugin}.lv2")
    if not os.path.isdir(bundle):
        return None
    kb = int(subprocess.check_output(["du", "-sk", "--apparent-size", bundle]).split()[0])
    return f"{kb / 1024:.1f} MB" if kb >= 1024 else f"{kb} KB"


def install_sh(plugin):
    with open(os.path.join(ROOT, "plugins", plugin, "scripts", "install.sh"), encoding="utf-8") as f:
        return f.read()


def user_presets_bank(plugin):
    """Name of the user presets bank that the plugin's own install creates, or empty"""
    m = re.search(r"presets/lv2/([\w-]+)\.presets\.lv2", install_sh(plugin))
    if not m and plugin == "weave4":   # created by scripts/register-factory-presets.py
        return "Eka_Weave-4"
    return m.group(1) if m else ""


def widget_links(plugin, widget):
    """Names that the plugin's own install gives the widget in zyngui/widgets_user"""
    if not widget:
        return []
    if plugin == "weave4":   # its widget module also defines the class for the plugin name "Eka Weave-4"
        return [widget, "zynthian_widget_eka_weave-4.py"]
    return [widget]


def yml_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("version", help="release tag, e.g. 0.1")
    ap.add_argument("--repo", default="dmtry3/zynthian-eka", help="GitHub repository with the releases")
    ap.add_argument("--author", default="dmtry3")
    args = ap.parse_args()

    sections = readme_sections()
    for plugin in sorted(os.listdir(os.path.join(ROOT, "plugins"))):
        if plugin not in sections:
            print(f"WARNING: no section for plugins/{plugin} in README.md, skipped")
            continue
        title, subtitle, para = sections[plugin]
        pdir = os.path.join(PKG_DIR, title)
        os.makedirs(pdir, exist_ok=True)

        # Size: measured, else the one already there
        size = installed_size(plugin)
        info_path = os.path.join(pdir, "info.yml")
        if size is None and os.path.isfile(info_path):
            with open(info_path, encoding="utf-8") as f:
                m = re.search(r'^size: "(.*)"', f.read(), re.M)
            size = m.group(1) if m else None
        size = size or "unknown"

        # Icon: the first screenshot of the plugin
        icon_line = ""
        shots = sorted(glob.glob(os.path.join(ROOT, "plugins", plugin, "docs", "1-*.png")))
        if shots:
            art = os.path.join(pdir, "Art")
            os.makedirs(art, exist_ok=True)
            icon = f"eka_{plugin}.png"
            shutil.copy2(shots[0], os.path.join(art, icon))
            icon_line = f'icon: "Art/{icon}"\n'

        widgets = glob.glob(os.path.join(ROOT, "plugins", plugin, "ui", "zynthian_widget_*.py")) + \
            glob.glob(os.path.join(ROOT, "plugins", plugin, "widget", "zynthian_widget_*.py"))
        widget = os.path.basename(widgets[0]) if widgets else ""
        has_samples = os.path.isdir(os.path.join(ROOT, "plugins", plugin, "samples"))
        with open(os.path.join(pdir, f"{title}.sh"), "w", encoding="utf-8") as f:
            f.write(SCRIPT.format(
                title=title, repo=args.repo, plugin=plugin, version=args.version, uri=plugin_uri(plugin),
                widget=widget, widget_links=" ".join(f'"{w}"' for w in widget_links(plugin, widget)),
                user_presets=user_presets_bank(plugin),
                samples_note=f" and its factory samples, linked as zynthian-my-data/files/Samples/eka-{plugin}"
                if has_samples else "",
                samples_var=f'# Factory samples: zynthian-my-data/files/Samples/<SAMPLES> (and <SAMPLES>-user for yours)\n'
                f'SAMPLES="eka-{plugin}"\n' if has_samples else 'SAMPLES=""\n'))
        short = subtitle[0].upper() + subtitle[1:]
        with open(info_path, "w", encoding="utf-8") as f:
            f.write(INFO.format(title=title, version=args.version, icon_line=icon_line, author=args.author,
                                repo=args.repo, size=size, plugin=plugin, short=yml_escape(short),
                                long=yml_escape(para)))
        print(f"{title}: {args.version}, {size}{'' if icon_line else ', no icon (no docs/1-*.png)'}")


if __name__ == "__main__":
    main()
